    @Override
    public void setupAnim(EldritchGolemRenderState state) {
        super.setupAnim(state);
        this.Head.yRot = state.yRot * Mth.DEG_TO_RAD / (state.headless ? 1.0F : 4.0F);
        this.Head.xRot = state.xRot * Mth.DEG_TO_RAD / (state.headless ? 1.0F : 2.0F);
        if (state.spawnTimer > 0 && !state.headless) {
            this.Head.yRot = 0.0F;
            this.Head.xRot = state.spawnTimer / 2.0F / (180.0F / Mth.PI);
        }
        this.Head.visible = !state.headless;
        this.Head2.visible = state.headless;
        this.Head2.yRot = state.yRot * Mth.DEG_TO_RAD;
        this.Head2.xRot = state.xRot * Mth.DEG_TO_RAD;
        if (state.attackTimer > 0) {
            float swing = (Math.abs((state.attackTimer - state.partialTick) % 10.0F - 5.0F) - 2.5F) / 2.5F;
            this.ArmR.xRot = -2.0F + 1.5F * swing;
            this.ArmL.xRot = -2.0F + 1.5F * swing;
        } else {
            this.ArmR.xRot = Mth.cos(state.walkAnimationPos * 0.4F + Mth.PI) * 2.0F * state.walkAnimationSpeed * 0.5F;
            this.ArmL.xRot = Mth.cos(state.walkAnimationPos * 0.4F) * 2.0F * state.walkAnimationSpeed * 0.5F;
        }
        this.LegR.xRot = Mth.cos(state.walkAnimationPos * 0.4662F) * 1.4F * state.walkAnimationSpeed;
        this.LegL.xRot = Mth.cos(state.walkAnimationPos * 0.4662F + Mth.PI) * 1.4F * state.walkAnimationSpeed;
        float stride = Math.min(Mth.cos(state.walkAnimationPos * 0.44F) * 1.4F * state.walkAnimationSpeed, Mth.cos(state.walkAnimationPos * 0.44F + Mth.PI) * 1.4F * state.walkAnimationSpeed);
        this.Frontcloth1.xRot = stride - 0.1047198F;
        this.Frontcloth2.xRot = stride - 0.3316126F;
        this.Cloak1.xRot = -stride / 3.0F + 0.1396263F;
        this.Cloak2.xRot = -stride / 3.0F + 0.3069452F;
        this.Cloak3.xRot = -stride / 3.0F + 0.4465716F;
    }
